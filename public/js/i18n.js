/** Locales réellement gérées : le reste retombe sur le français. */
export const LOCALES = ["fr", "en"];
let locale = "fr";
const listeners = new Set();

/** Clés disponibles dans une langue — sert aux tests d'intégrité du dictionnaire. */
export function dictionaryKeys(next = locale) {
  return Object.keys(DICT[next] ?? DICT.fr);
}

export function getLocale() {
  return locale;
}

/** Change la langue de l'interface et prévient ceux qui l'affichent. */
export function setLocale(next) {
  const value = LOCALES.includes(next) ? next : "fr";
  if (value === locale) return value;
  locale = value;
  if (typeof document !== "undefined") document.documentElement.lang = value;
  listeners.forEach((fn) => fn(value));
  return value;
}

export function onLocaleChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * Traduit une clé. `{n}` et `{what}` sont remplacés par `vars`.
 * Une clé absente retombe sur le français, puis sur la clé elle-même : une
 * traduction manquante se voit immédiatement plutôt que d'afficher du vide.
 */
export function t(key, vars) {
  const table = DICT[locale] ?? DICT.fr;
  const template = table[key] ?? DICT.fr[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Remplit `{n}` sans écrire la clé en dur dans le code appelant. */
export const count = (key, n, vars) => t(key, { ...vars, n });

/**
 * Applique les traductions déclarées dans le DOM.
 * - data-i18n        → textContent
 * - data-i18n-html   → innerHTML (dictionnaire de confiance uniquement)
 * - data-i18n-attr   → « placeholder:clé, title:clé »
 */
export function applyI18n(root = document) {
  if (!root?.querySelectorAll) return;
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll("[data-i18n-html]")) {
    el.innerHTML = t(el.dataset.i18nHtml);
  }
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(",")) {
      const [attr, key] = pair.split(":").map((part) => part.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}

/** Les <option> de la langue suivent la langue (elles se remplissent en JS). */
export function refreshOptions(select, options, current) {
  if (!select) return;
  const active = current ?? select.value;
  select.innerHTML = options
    .map((option) => `<option value="${option.value}">${option.label}</option>`)
    .join("");
  select.value = active;
}